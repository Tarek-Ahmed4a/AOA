import type { AnatomicalSystem } from '../store/useAnatomyStore';
import type {
  AnatomicalFiducialLandmark,
  LandmarkSnapDirection,
  LandmarkVisualVariant,
} from './anatomicalLandmarksCatalog';

type Laterality = 'Left' | 'Right' | 'Median / Unpaired';

interface CompactLandmarkSpec {
  id: string;
  en: string;
  ar: string;
  lat: string;
  sys: AnatomicalSystem;
  var?: LandmarkVisualVariant;
  variant?: LandmarkVisualVariant;
  side: Laterality;
  reg: string;
  orgEn: string;
  orgAr: string;
  mesh: string[];
  excl?: string[];
  exp: string[];
  off?: [number, number, number];
  ratio?: [number, number, number];
  dir?: LandmarkSnapDirection;
  locEn: string;
  locAr: string;
  sigEn: string;
  sigAr: string;
}

function ratioToOffset(ratio: [number, number, number]): [number, number, number] {
  return [
    Number((ratio[0] - 0.5).toFixed(3)),
    Number((ratio[1] - 0.5).toFixed(3)),
    Number((ratio[2] - 0.5).toFixed(3)),
  ];
}

function buildLandmark(s: CompactLandmarkSpec): AnatomicalFiducialLandmark {
  const off = s.off ?? (s.ratio ? ratioToOffset(s.ratio) : [0, 0, 0]);
  return {
    id: s.id,
    nameEn: s.en,
    nameAr: s.ar,
    latinName: s.lat,
    system: s.sys,
    variant: s.variant ?? s.var ?? 'amber',
    laterality: s.side,
    region: s.reg,
    parentOrganLabel: s.orgEn,
    parentOrganAr: s.orgAr,
    meshMatchPatterns: s.mesh,
    excludePatterns: s.excl,
    explorerModelPatterns: s.exp,
    normalizedOffset: off,
    anatomicalRatio: s.ratio,
    snapDirection: s.dir ?? 'outward',
    localizationEn: s.locEn,
    localizationAr: s.locAr,
    significanceEn: s.sigEn,
    significanceAr: s.sigAr,
  };
}

function pairRatioLR(
  baseId: string,
  enBase: string,
  arBase: string,
  latBase: string,
  reg: string,
  orgBaseEn: string,
  orgBaseAr: string,
  meshBase: string[],
  expBase: string[],
  ratioLeft: [number, number, number],
  locEn: string,
  locAr: string,
  sigEn: string,
  sigAr: string,
  variant: LandmarkVisualVariant = 'amber',
  sys: AnatomicalSystem = 'skeletal',
  excl?: string[]
): AnatomicalFiducialLandmark[] {
  const offLeft = ratioToOffset(ratioLeft);
  return [
    buildLandmark({
      id: `${baseId}-left`,
      en: `${enBase} (Left)`,
      ar: `${arBase} (الأيسر)`,
      lat: `${latBase} sinister`,
      sys,
      variant,
      side: 'Left',
      reg,
      orgEn: `${orgBaseEn} (Left)`,
      orgAr: `${orgBaseAr} (الأيسر)`,
      mesh: meshBase,
      excl,
      exp: expBase,
      off: offLeft,
      ratio: ratioLeft,
      locEn: `Left side: ${locEn}`,
      locAr: `الجانب الأيسر: ${locAr}`,
      sigEn,
      sigAr,
    }),
    buildLandmark({
      id: `${baseId}-right`,
      en: `${enBase} (Right)`,
      ar: `${arBase} (الأيمن)`,
      lat: `${latBase} dexter`,
      sys,
      variant,
      side: 'Right',
      reg,
      orgEn: `${orgBaseEn} (Right)`,
      orgAr: `${orgBaseAr} (الأيمن)`,
      mesh: meshBase,
      excl,
      exp: expBase,
      off: [-offLeft[0], offLeft[1], offLeft[2]],
      ratio: ratioLeft,
      locEn: `Right side: ${locEn}`,
      locAr: `الجانب الأيمن: ${locAr}`,
      sigEn,
      sigAr,
    }),
  ];
}

