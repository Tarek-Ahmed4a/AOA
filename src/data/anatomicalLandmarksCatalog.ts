/**
 * Generates bilingual clinical details and parent-organ metadata when clicking any
 * NIH HRA `.glb` surgical landmark (`ta98Code === 'HRA-LMK'`) or fiducial beacon (`LMK-FID`).
 */
export function resolveHraSubmeshClinicalCopy(
  landmarkTitle: string,
  parentOrganLabel: string,
  subNode = ''
): {
  nameAr: string;
  significanceEn: string;
  significanceAr: string;
  localizationEn: string;
  localizationAr: string;
} {
  const txt = `${landmarkTitle} ${subNode}`.toLowerCase();
  const orgLower = parentOrganLabel.toLowerCase();

  let parentAr = parentOrganLabel;
  if (/heart/.test(orgLower)) parentAr = 'القلب';
  else if (/left kidney/.test(orgLower)) parentAr = 'الكلية اليسرى';
  else if (/right kidney/.test(orgLower)) parentAr = 'الكلية اليمنى';
  else if (/kidney/.test(orgLower)) parentAr = 'الكلية';
  else if (/liver/.test(orgLower)) parentAr = 'الكبد';
  else if (/lung/.test(orgLower)) parentAr = 'الرئة';
  else if (/spleen/.test(orgLower)) parentAr = 'الطحال';
  else if (/pancreas/.test(orgLower)) parentAr = 'البنكرياس';
  else if (/small intestine/.test(orgLower)) parentAr = 'الأمعاء الدقيقة';
  else if (/large intestine|colon/.test(orgLower)) parentAr = 'الأمعاء الغليظة (القولون)';
  else if (/urinary bladder|bladder/.test(orgLower)) parentAr = 'المثانة البولية';
  else if (/uterus/.test(orgLower)) parentAr = 'الرحم';
  else if (/left ovary/.test(orgLower)) parentAr = 'المبيض الأيسر';
  else if (/right ovary/.test(orgLower)) parentAr = 'المبيض الأيمن';
  else if (/left fallopian/.test(orgLower)) parentAr = 'قناة فالوب اليسرى';
  else if (/right fallopian/.test(orgLower)) parentAr = 'قناة فالوب اليمنى';
  else if (/left mammary/.test(orgLower)) parentAr = 'الغدة الثديية اليسرى';
  else if (/right mammary/.test(orgLower)) parentAr = 'الغدة الثديية اليمنى';
  else if (/prostate/.test(orgLower)) parentAr = 'غدة البروستات';
  else if (/larynx/.test(orgLower)) parentAr = 'الحنجرة';
  else if (/trachea/.test(orgLower)) parentAr = 'الرغامى';
  else if (/main bronchus/.test(orgLower)) parentAr = 'القصبة الهوائية الرئيسية';
  else if (/spinal cord/.test(orgLower)) parentAr = 'الحبل الشوكي';
  else if (/left eye/.test(orgLower)) parentAr = 'العين اليسرى';
  else if (/right eye/.test(orgLower)) parentAr = 'العين اليمنى';
  else if (/knee/.test(orgLower)) parentAr = 'مفصل الركبة';
  else if (/ureter/.test(orgLower)) parentAr = 'الحالب';
  else if (/mouth/.test(orgLower)) parentAr = 'جوف الفم';
  else if (/tonsil/.test(orgLower)) parentAr = 'اللوزة الحنكية';

  let subAr = landmarkTitle;
  let sigEn = `Official NIH Human Reference Atlas surgical/CCF fiducial marking a critical anatomical boundary or functional compartment on the ${parentOrganLabel}. Used for reproducible biopsy localization, sectional surgery planning, and spatial registration.`;
  let sigAr = `معلم جراحي وتشريحي مرجعي من أطلس NIH البشري على (${parentAr}) لتحديد الحدود التشريحية الدقيقة ومسارات أخذ العينات والتخطيط الجراحي.`;

  if (/arter|coronary|aort/.test(txt)) {
    subAr = `${parentAr}: معلم التروية الشريانية`;
    sigEn = `Arterial vascular landmark on ${parentOrganLabel} critical for clamping tolerance, segmental perfusion territories, and avoiding catastrophic intraoperative hemorrhage or ischemia.`;
    sigAr = `معلم التروية الشريانية في ${parentAr}؛ أساسي لتحديد الأجزاء الترووية وتفادي النزف الحاد أو الاحتشاء أثناء التداخل الجراحي.`;
  } else if (/vein|venous|vena|portal/.test(txt)) {
    subAr = `${parentAr}: معلم التصريف الوريدي`;
    sigEn = `Venous drainage landmark of ${parentOrganLabel} guiding vascular control, venous thromboembolism assessment, and retroperitoneal or parenchymal dissection planes.`;
    sigAr = `معلم التصريف الوريدي في ${parentAr}؛ يوجّه الجراح للسيطرة الوريدية وتفادي التمزق الوريدي خلال التسليخ.`;
  } else if (/bisection|plane|mid|coronal|sagittal|transverse|axis|border/.test(txt)) {
    subAr = `${parentAr}: مستوى الانقسام أو الحدود التشريحية`;
    sigEn = `CCF surgical reference plane partitioning ${parentOrganLabel} into standardized anatomical sectors for stereotactic registration, lobectomy, or partial organ resection.`;
    sigAr = `مستوى تشريحي معياري يقسّم ${parentAr} إلى قطاعات جراحية قياسية للمطابقة المكانية والاستئصال الجزئي المنظم.`;
  } else if (/cortex|medulla|capsule|pelvis|calyx|ureter|hilum/.test(txt)) {
    subAr = `${parentAr}: معلم النسيج والحدود الوظيفية`;
    sigEn = `Structural parenchymal/hilar landmark within ${parentOrganLabel} distinguishing outer functional zones from central collecting, ductal, or neurovascular pedicle entry points.`;
    sigAr = `معلم بنيوي يميز الطبقات الوظيفية من السرة والمجاري المفرغة أو الحزمة الوعائية العصبية في ${parentAr}.`;
  } else if (/nerve|optic|dura/.test(txt)) {
    subAr = `${parentAr}: معلم العصب أو الغلاف العصبي`;
    sigEn = `Neural/dural landmark associated with ${parentOrganLabel} where intraoperative traction, thermal spread, or compression risks sensory or motor deficit.`;
    sigAr = `معلم عصبي مرتبط بـ ${parentAr} يتطلب حماية دقيقة أثناء التسليخ الجراحي لمنع الأذية العصبية الدائمة.`;
  } else if (/atrium|ventricle|valve|septum/.test(txt)) {
    subAr = `${parentAr}: معلم الحجرة أو الصمام القلبي`;
    sigEn = `Intracardiac chamber/valvular landmark anchoring hemodynamic pressure gradients, interventional catheter navigation, and surgical valve/septal repair.`;
    sigAr = `معلم حجري أو صمامي في القلب يحدد مسار القسطرة التداخلية وترميم الصمامات والحاجز القلبي.`;
  } else if (/lobe|fissure|bronch/.test(txt)) {
    subAr = `${parentAr}: الفص أو الشق أو التفرع القصبي`;
    sigEn = `Pulmonary/bronchial anatomical partition used to plan anatomical lobectomy, sublobar segmentectomy, and bronchoscopic lesion targeting.`;
    sigAr = `معلم فصّي أو قصبي في ${parentAr} يوجّه جراحات استئصال الفصوص والملاحة التنظيرية للقصبات.`;
  }

  return {
    nameAr: `${landmarkTitle} (${subAr})`,
    significanceEn: sigEn,
    significanceAr: sigAr,
    localizationEn: `Official NIH HRA spatial fiducial anchored directly to ${parentOrganLabel}${subNode ? ` (node: ${subNode})` : ''}.`,
    localizationAr: `معلم مرجعي مكاني مرتبط مباشرة بـ ${parentAr}.`,
  };
}

export function buildLandmarkClinicalProfile(
  part: AnatomicalPartInfo
): AnatomicalClinicalProfile {
  const meta = part.landmarkMeta;
  const nameEn = meta?.nameEn || part.cleanName;
  const fallback =
    meta ??
    (() => {
      const parentOrganLabel =
        part.latinName.replace(/^NIH HRA Fiducial\s*•\s*/i, '') ||
        'Target Organ';
      const resolved = resolveHraSubmeshClinicalCopy(
        part.cleanName,
        parentOrganLabel,
        part.rawName
      );
      return {
        id: part.rawName,
        nameEn: part.cleanName,
        nameAr: resolved.nameAr,
        latinName: part.latinName,
        parentOrganLabel,
        parentOrganAr: parentOrganLabel,
        localizationEn: resolved.localizationEn,
        localizationAr: resolved.localizationAr,
        significanceEn: resolved.significanceEn,
        significanceAr: resolved.significanceAr,
        region: 'Clinical / Surgical Fiducial',
      };
    })();

  return {
    id: part.rawName || part.meshUuid,
    cleanNameEn: nameEn,
    cleanNameAr: part.cleanNameAr || fallback.nameAr,
    latinName: fallback.latinName || part.latinName,
    ta98Code: part.ta98Code || 'LMK-FID',
    system: part.system,
    laterality: part.laterality,
    region: fallback.region || 'Surgical & Surface Anatomy',
    summaryEn:
      fallback.localizationEn ||
      `High-yield anatomical & surgical landmark anchored to ${fallback.parentOrganLabel}.`,
    summaryAr:
      fallback.localizationAr ||
      `معلم تشريحي وجراحي مرجعي مرتبط بـ ${fallback.parentOrganAr || fallback.parentOrganLabel}.`,
    primaryFunctionEn: `Spatial surgical/clinical orientation landmark on ${fallback.parentOrganLabel}`,
    primaryFunctionAr: `نقطة توجيه سريرية وجراحية دقيقة على ${fallback.parentOrganAr || fallback.parentOrganLabel}`,
    relationsEn: `Parent Structure: ${fallback.parentOrganLabel}`,
    relationsAr: `العضو المرتبط: ${fallback.parentOrganAr || fallback.parentOrganLabel}`,
    arterialSupply: `Segmental perfusion aligned with ${fallback.parentOrganLabel}`,
    venousDrainage: `Regional venous plexus of ${fallback.parentOrganLabel}`,
    innervation: `Regional somatic/autonomic innervation of ${fallback.parentOrganLabel}`,
    clinicalNotesEn: fallback.significanceEn,
    clinicalNotesAr: fallback.significanceAr,
    bookSourceLabel: 'Clinical Surgical Landmarks Atlas',
    source: 'clinical-baseline',
  };
}
